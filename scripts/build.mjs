// Scans works/<section>/ and writes assets/works.js for the site.
// Rules:
//   - A file directly in a section folder = one work.
//   - A sub-folder = one work with several images (e.g. a catalog's pages, a logo + mockups).
//   - Title comes from the file/folder name: "01-coffee-brand.jpg" -> "Coffee Brand".
//     A leading number ("01-") only controls order and is hidden.
//   - Videos: an image with the same name (e.g. intro.mp4 + intro.jpg) is used as its cover.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, extname, basename } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SECTIONS = ["motion", "posters", "logos", "catalogs"];
const IMG = [".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif", ".svg"];
const VID = [".mp4", ".webm", ".mov"];
const MAX_MB = 50;
const errors = [];

const nat = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
const visible = (n) => !n.startsWith(".") && !n.startsWith("_");
const stem = (n) => basename(n, extname(n));
const title = (n) =>
  stem(n).replace(/^\d+[\s._-]*/, "").replace(/[_-]+/g, " ").trim()
    .replace(/\b\p{Ll}/gu, (c) => c.toUpperCase()) || stem(n);
const url = (...p) => p.map(encodeURIComponent).join("/");

function checkSize(path) {
  const mb = statSync(path).size / 1048576;
  if (mb > MAX_MB) errors.push(`${path} is ${mb.toFixed(1)} MB (max ${MAX_MB} MB) — compress it.`);
}

const data = {};
for (const section of SECTIONS) {
  const dir = join(ROOT, "works", section);
  let names = [];
  try { names = readdirSync(dir).filter(visible).sort(nat); } catch { /* folder missing */ }
  const items = [];
  const used = new Set();

  for (const name of names) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      const files = readdirSync(full).filter(visible).sort(nat)
        .filter((f) => IMG.includes(extname(f).toLowerCase()));
      files.forEach((f) => checkSize(join(full, f)));
      if (files.length) items.push({ type: "gallery", title: title(name), _n: name,
        images: files.map((f) => url("works", section, name, f)) });
      continue;
    }
    const ext = extname(name).toLowerCase();
    checkSize(full);
    if (VID.includes(ext)) {
      const cover = names.find((n) => stem(n) === stem(name) && IMG.includes(extname(n).toLowerCase()));
      if (cover) used.add(cover);
      items.push({ type: "video", title: title(name), _n: name, src: url("works", section, name),
        cover: cover ? url("works", section, cover) : null });
    }
  }
  for (const name of names) {
    const ext = extname(name).toLowerCase();
    if (IMG.includes(ext) && !used.has(name) && statSync(join(dir, name)).isFile())
      items.push({ type: "image", title: title(name), src: url("works", section, name), _n: name });
  }
  // keep folder order: re-sort everything by original name
  items.sort((a, b) => nat(a._n, b._n));
  items.forEach((i) => delete i._n);
  data[section] = items;
}

if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
writeFileSync(join(ROOT, "assets", "works.js"),
  `// Generated by scripts/build.mjs — do not edit by hand.\nwindow.WORKS = ${JSON.stringify(data, null, 2)};\n`);
console.log(Object.entries(data).map(([k, v]) => `${k}: ${v.length}`).join(" | "));
